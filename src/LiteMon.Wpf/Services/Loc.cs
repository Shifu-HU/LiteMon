/// <summary>
/// 界面文案三语（zh / en / ja）。静态字典 + T(key)：
/// 页面构造时取值（与主题切换一样走"页面重建"机制换语言，无需绑定系统）。
/// 未命中的 key 原样返回（开发期可见漏翻）。
/// </summary>
public static class Loc
{
    private static Dictionary<string, string> _map = Zh;
    private static string _lang = "zh";

    /// <summary>
    /// 可选语言（下拉菜单用）。含联合国六种官方语言（ar/zh/en/fr/ru/es）+ 日语，共 7 种。
    /// </summary>
    public static readonly List<(string Code, string Name)> Available = new()
    {
        ("zh", "简体中文"),
        ("en", "English"),
        ("ja", "日本語"),
        ("fr", "Français"),
        ("ru", "Русский"),
        ("es", "Español"),
        ("ar", "العربية"),
    };

    /// <summary>当前语言代码（zh/en/ja/fr/ru/es/ar）。切换后需重建页面（同主题切换机制）。</summary>
    public static string Language
    {
        get => _lang;
        set
        {
            _lang = value switch
            {
                "en" => "en",
                "ja" => "ja",
                "fr" => "fr",
                "ru" => "ru",
                "es" => "es",
                "ar" => "ar",
                _ => "zh",
            };
            _map = _lang switch
            {
                "en" => En,
                "ja" => Ja,
                "fr" => Fr,
                "ru" => Ru,
                "es" => Es,
                "ar" => Ar,
                _ => Zh,
            };
        }
    }

    /// <summary>当前语言是否从右到左书写（阿拉伯语）。窗口据此设置 FlowDirection。</summary>
    public static bool IsRtl => _lang == "ar";

    /// <summary>取文案；未命中返回 key 本身。</summary>
    public static string T(string key) => _map.TryGetValue(key, out var v) ? v : key;

    /// <summary>带格式化参数的文案。</summary>
    public static string T(string key, params object[] args) => string.Format(System.Globalization.CultureInfo.CurrentCulture, T(key), args);

